"""Resend HTTPS email delivery, with a local fallback when no key is configured.

Success means accepted by Resend, NOT delivered to an inbox. Resend's email log
is the source of delivery/bounce status until authenticated webhooks are added.

No RESEND_API_KEY (blank/unset) is a supported, non-fatal state for local demos:
send_email() writes the alert to LOCAL_OUTBOX and stdout instead of calling Resend.
Set a real key to send through Resend; a key that IS set but malformed is still
a hard config error (MailError), since that's a mistake, not "no key configured".

The incident report is the human review surface (PLAN B6). `prepare_message(incident)`
alone renders the raise-time message the blue agent queues; `report_context(incident)`
gathers what the agent saw/did, what changed, the audit head and the case-file deep
link from the store, and `prepare_message(incident, context)` renders the full report.
The mail worker does that enrichment once, on the first delivery attempt.
"""
import hashlib
import html
import json
import os
from datetime import datetime, timedelta, timezone
from email.utils import getaddresses
from pathlib import Path

import httpx

from bastion import store
from bastion.privacy import redact

try:  # cross-workstream modules (CONTRACTS §4.1): the report degrades without them
    from bastion import audit
except Exception:  # pragma: no cover - exercised by monkeypatching to None in tests
    audit = None
try:
    from bastion import rollback
except Exception:  # pragma: no cover
    rollback = None

LOCAL_OUTBOX = Path(os.getenv("BASTION_DATA_DIR", str(Path(__file__).resolve().parent.parent / "data"))) / "local_mail.jsonl"
DEFAULT_DASHBOARD_URL = "http://localhost:8080"
FOOTER = "Generated by Bastion. Provider acceptance does not guarantee inbox delivery."
# Operator-language names for the agent's tools (same wording as the case file).
TOOL_LABELS = {
    "blacklist_ip": "Banned source", "bulk_blacklist_ip": "Banned sources", "unban_ip": "Lifted ban",
    "divert_to_honeypot": "Diverted source to honeypot", "undivert": "Released honeypot diversion",
    "virtual_patch": "Virtual-patched route at the proxy", "patch_vuln": "Raised target security level",
    "quarantine_container": "Quarantined container", "release_container": "Released container",
    "isolate_egress": "Cut outbound network", "reconnect_egress": "Reconnected outbound network",
    "kill_process": "Killed process", "kill_session": "Invalidated session", "rotate_secret": "Rotated credential",
    "raise_alert": "Raised this incident", "rollback": "Rolled back an earlier action",
    "operator_policy": "Operator changed policy", "inspect_target": "Inspected recorded request",
    "recent_requests": "Reviewed recent requests", "recent_incidents": "Reviewed recent incidents",
    "get_defenses": "Reviewed active defenses", "service_status": "Checked service status",
    "list_processes": "Listed processes", "list_sessions": "Listed sessions",
}
READ_ONLY_TOOLS = {"inspect_target", "recent_requests", "recent_incidents", "get_defenses",
                   "service_status", "list_processes", "list_sessions"}
# Parameters worth a reviewer's glance, in display order; everything else stays in the case file.
PARAM_KEYS = ("ip", "ips", "path", "attack_type", "pattern", "level", "target", "pid", "session_id",
              "severity", "reverts", "inverse", "reason")
MAX_REPORT_ACTIONS = 50
TREND_DAYS = 30


class MailError(Exception):
    """Safe error suitable for logs; never includes provider response bodies."""
    def __init__(self, message, retryable=True, retry_after=None):
        super().__init__(message)
        self.retryable = retryable
        self.retry_after = retry_after


def _addresses(value):
    if not value or "\r" in value or "\n" in value:
        raise MailError("Set valid ALERT_FROM and ALERT_TO addresses", retryable=False)
    parsed = getaddresses([value])
    if not parsed or any(not address or address.count("@") != 1 or any(c.isspace() for c in address)
                         or not all(address.split("@")) for _, address in parsed):
        raise MailError("Invalid alert email address", retryable=False)
    return parsed


def validate_config():
    """Return the Resend key, None to use the local fallback, or raise on a bad key."""
    key = os.getenv("RESEND_API_KEY", "").strip()
    if not key:
        return None
    if not key.startswith("re_") or len(key) < 10 or key in {"re_...", "re_your_key"}:
        raise MailError("RESEND_API_KEY is set but invalid; fix it in .env or clear it to use the local fallback", retryable=False)
    return key


def dashboard_url():
    return (os.getenv("PUBLIC_DASHBOARD_URL", "").strip() or DEFAULT_DASHBOARD_URL).rstrip("/")


def case_file_link(incident_id):
    """Deep link into the authenticated case file (CONTRACTS §3.4); the incident list when unknown."""
    base = dashboard_url() + "/__dash#/incidents"
    return f"{base}/{int(incident_id)}" if isinstance(incident_id, int) else base


def _case_ids(case_id):
    """The case id plus each contributing event id (triage rows are keyed per event)."""
    case_id = str(case_id or "")
    return list(dict.fromkeys([case_id] + [p.strip() for p in case_id.split(",") if p.strip()]))


def _parse_ts(value):
    try:
        return datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None


def _format_param(key, value):
    if key == "ips" and isinstance(value, list):
        shown = ", ".join(str(ip) for ip in value[:5])
        return f"{len(value)} sources ({shown}{', …' if len(value) > 5 else ''})"
    if isinstance(value, (dict, list)):
        value = json.dumps(value, ensure_ascii=False)
    value = str(value).replace("\r", " ").replace("\n", " ")
    limit = 160 if key == "reason" else 80
    return value if len(value) <= limit else value[:limit - 1] + "…"


def reversibility(record):
    """One phrase per action: reversible via the rollback inverse map, reverted, or not."""
    tool = record.get("tool")
    if record.get("kind") != "action" or tool in READ_ONLY_TOOLS:
        return "not applicable (read-only)"
    if record.get("reverted_by") is not None:
        return f"already reverted by action #{record['reverted_by']}"
    if record.get("outcome") != "ok":
        return "nothing to revert (did not take effect)"
    if rollback is None:
        return "reversibility unknown (rollback module unavailable)"
    if tool in rollback.INVERSE:
        return f"reversible (inverse: {rollback.INVERSE[tool]})"
    if tool in rollback.IRREVERSIBLE:
        return "irreversible"
    return "not reversible"


def humanize_action(record):
    inp = record.get("input") if isinstance(record.get("input"), dict) else {}
    params = "; ".join(f"{key}={_format_param(key, inp[key])}" for key in PARAM_KEYS if key in inp and inp[key] not in (None, ""))
    tool = str(record.get("tool") or record.get("kind") or "unknown")
    return {"id": record.get("id"), "ts": str(record.get("ts", "")), "tool": tool,
            "label": TOOL_LABELS.get(tool, tool.replace("_", " ").capitalize()),
            "params": params, "outcome": str(record.get("outcome", "unknown")), "reversibility": reversibility(record)}


def _case_records(db, case_id):
    ids = _case_ids(case_id)
    marks = ",".join("?" * len(ids))
    rows = db.execute("SELECT id,data FROM records WHERE kind='actions' AND "
                      f"COALESCE(case_id,json_extract(data,'$.case_id')) IN ({marks}) ORDER BY id", ids).fetchall()
    records = [{**json.loads(r["data"]), "id": r["id"]} for r in rows]
    if rollback is not None:
        records = rollback.annotate(records, rollback.reverted_map(db))
    return records


def _verdict(triage_rows):
    """The strongest classifier verdict recorded for the case, or None."""
    verdicts = [r.get("jev") for r in triage_rows if isinstance(r.get("jev"), dict)]
    if not verdicts:
        return None
    best = max(verdicts, key=lambda v: (bool(v.get("malicious")), float(v.get("malicious_score") or 0)))
    return {"malicious": bool(best.get("malicious")), "score": best.get("malicious_score"),
            "attack_type": best.get("attack_type"), "confidence": best.get("type_confidence")}


def _changes(actions, state):
    """Containment summary: what this case changed on the target and whether it still stands."""
    effective = [a for a in actions if a.get("kind") == "action" and a.get("outcome") == "ok" and a.get("reverted_by") is None]
    inputs = lambda tool: [a["input"] for a in effective if a.get("tool") == tool and isinstance(a.get("input"), dict)]  # noqa: E731
    banned_now = {d["ip"] for d in state.get("denylist", []) if store.active_ban(d)}
    diverted_now = {d.get("ip") for d in state.get("honeypot", [])}
    patched_now = {(r.get("path"), r.get("pattern")) for r in state.get("vpatch", [])}
    bans = [str(ip) for inp in inputs("blacklist_ip") for ip in [inp.get("ip")] if ip]
    bans += [str(ip) for inp in inputs("bulk_blacklist_ip") for ip in (inp.get("ips") or []) if isinstance(inp.get("ips"), list)]
    diversions = [str(inp.get("ip")) for inp in inputs("divert_to_honeypot") if inp.get("ip")]
    vpatches = []
    for inp in inputs("virtual_patch"):
        pattern = inp.get("pattern")
        try:
            from bastion.security import canonical_vpatch
            pattern = canonical_vpatch(inp.get("attack_type")) or pattern
        except Exception:
            pass
        vpatches.append({"path": str(inp.get("path")), "attack_type": str(inp.get("attack_type") or "custom"),
                         "active": (inp.get("path"), pattern) in patched_now})
    levels = [str(inp.get("level")) for inp in inputs("patch_vuln") if inp.get("level")]
    return {"security_level": {"requested": levels[-1] if levels else None, "enforced": state.get("enforced_security")},
            "virtual_patches": vpatches,
            "bans": [{"ip": ip, "active": ip in banned_now} for ip in dict.fromkeys(bans)],
            "diversions": [{"ip": ip, "active": ip in diverted_now} for ip in dict.fromkeys(diversions)],
            "quarantined": [str(inp.get("target")) for inp in inputs("quarantine_container")],
            "egress_cut": [str(inp.get("target")) for inp in inputs("isolate_egress")],
            "irreversible": [humanize_action(a) for a in effective if rollback is not None and a.get("tool") in rollback.IRREVERSIBLE]}


def _trend(db, at):
    """Incidents raised in the last TREND_DAYS versus the TREND_DAYS before (from the store)."""
    recent_from = (at - timedelta(days=TREND_DAYS)).strftime("%Y-%m-%dT%H:%M:%SZ")
    previous_from = (at - timedelta(days=2 * TREND_DAYS)).strftime("%Y-%m-%dT%H:%M:%SZ")
    row = db.execute("SELECT COALESCE(SUM(ts>=?),0) AS recent, COALESCE(SUM(ts>=? AND ts<?),0) AS previous "
                     "FROM records WHERE kind='incidents' AND ts>=?", (recent_from, previous_from, recent_from, previous_from)).fetchone()
    return {"days": TREND_DAYS, "recent": int(row["recent"]), "previous": int(row["previous"])}


def report_context(incident):
    """Everything the review surface needs beyond the raise-time incident dict, read from the store.

    Each part degrades independently: a missing audit/rollback module or an empty action list
    renders as such, never as a failed send.
    """
    case_id = incident.get("case_id")
    with store.connection() as db:
        incident_id = incident.get("id")
        if not isinstance(incident_id, int) and case_id is not None:
            row = db.execute("SELECT id FROM records WHERE kind='incidents' AND COALESCE(case_id,json_extract(data,'$.case_id'))=? "
                             "AND (? IS NULL OR ts=?) AND (? IS NULL OR json_extract(data,'$.attack_type')=?) ORDER BY id DESC LIMIT 1",
                             (str(case_id), incident.get("ts"), incident.get("ts"),
                              incident.get("attack_type"), incident.get("attack_type"))).fetchone()
            incident_id = row["id"] if row else None
        records = _case_records(db, case_id) if case_id is not None else []
        trend = _trend(db, _parse_ts(incident.get("ts")) or datetime.now(timezone.utc))
    actions = [humanize_action(r) for r in records if r.get("kind") != "triage"]
    head = None
    if audit is not None:
        try:
            head = audit.head()
        except Exception:
            head = None
    return redact({"incident_id": incident_id, "link": case_file_link(incident_id),
                   "verdict": _verdict([r for r in records if r.get("kind") == "triage"]),
                   "actions": actions, "changes": _changes(records, store.load_state()),
                   "audit": head, "rollback_available": rollback is not None, "trend": trend})


def _trend_line(trend):
    recent, previous, days = trend["recent"], trend["previous"], trend["days"]
    line = f"{recent} incident(s) in the last {days} days versus {previous} in the {days} days before"
    if previous == 0:
        return line + " (no earlier baseline yet)."
    change = (recent - previous) / previous * 100
    direction = "down" if change < 0 else "up" if change > 0 else "unchanged"
    return line + (" (unchanged)." if direction == "unchanged" else f" ({direction} {abs(round(change))}%).")


def _report_sections(incident, context):
    """Report body as (heading, [lines]); rendered to text and HTML by the callers."""
    verdict = context.get("verdict")
    if verdict:
        verdict_line = (f"Classifier verdict: {'malicious' if verdict['malicious'] else 'not malicious'}"
                        f" (score {verdict.get('score')}, type {verdict.get('attack_type') or 'unknown'},"
                        f" type confidence {verdict.get('confidence')})")
    else:
        verdict_line = "Classifier verdict: none recorded for this case"
    saw = [verdict_line, f"Attack type reported by the agent: {incident.get('attack_type', 'unknown')}",
           "Evidence excerpt: " + (str(incident.get("evidence", ""))[:600] or "(none)")]
    actions = context.get("actions") or []
    if actions:
        did = [f"{i}. {a['ts']}  {a['label']}" + (f" — {a['params']}" if a["params"] else "")
               + f" — outcome: {a['outcome']} — {a['reversibility']}"
               for i, a in enumerate(actions[:MAX_REPORT_ACTIONS], 1)]
        if len(actions) > MAX_REPORT_ACTIONS:
            did.append(f"… {len(actions) - MAX_REPORT_ACTIONS} more in the case file.")
    else:
        did = ["No actions are recorded for this case yet; the case file shows the live list."]
    changes = context.get("changes") or {}
    level = changes.get("security_level") or {}
    changed = ["Target security level: " + (f"{level['enforced']} (enforced)" if level.get("enforced")
                                            else f"{level['requested']} requested" if level.get("requested") else "unchanged")]
    vpatches = changes.get("virtual_patches") or []
    changed.append("Proxy virtual patches: " + ("; ".join(f"{v['path']} [{v['attack_type']}] "
                                                          f"{'active' if v['active'] else 'no longer active'}" for v in vpatches) or "none"))
    for label, key, verb in (("Bans", "bans", "lifted"), ("Honeypot diversions", "diversions", "released")):
        items = changes.get(key) or []
        changed.append(f"{label}: " + ("; ".join(f"{d['ip']} ({'active' if d['active'] else verb})" for d in items) or "none"))
    changed.append("Quarantine: " + (", ".join(changes.get("quarantined") or []) + " (paused)" if changes.get("quarantined") else "none"))
    changed.append("Outbound network: " + (", ".join(changes.get("egress_cut") or []) + " (cut)" if changes.get("egress_cut") else "unchanged"))
    if changes.get("irreversible"):
        changed.append("Irreversible actions taken: " + "; ".join(a["label"] + (f" — {a['params']}" if a["params"] else "")
                                                              for a in changes["irreversible"]))
    head = context.get("audit")
    if head and head.get("head"):
        verify = [f"Audit chain: {head['length']} chained action(s); head sha256 {head['head']}",
                  f"Re-verify any time (sign-in required): GET {dashboard_url()}/__api/v1/audit/verify"]
    elif head is not None:
        verify = ["Audit chain: no chained actions yet."]
    else:
        verify = ["Audit chain: not available in this deployment."]
    review = ["Open the case file to review each action and revert it from there (sign-in required):",
              context.get("link") or case_file_link(None)]
    if not context.get("rollback_available"):
        review.append("One-click rollback is not available in this deployment.")
    sections = [("What the agent saw", saw), (f"What it did ({len(actions)} action(s), chronological)", did),
                ("What changed on the target", changed), ("How to verify", verify), ("Review and roll back", review)]
    if context.get("trend"):
        sections.append(("Trend", [_trend_line(context["trend"])]))
    return sections


def _html_report(subject, intro, fields, sections):
    out = ["<h2>", html.escape(subject), "</h2><p>", html.escape(intro), "</p><table>"]
    for label, value in fields:
        out += ["<tr><th align=\"left\" valign=\"top\">", html.escape(label), "</th><td style=\"white-space:pre-wrap\">",
                html.escape(str(value)[:2000]), "</td></tr>"]
    out.append("</table>")
    for heading, lines in sections:
        out += ["<h3>", html.escape(heading), "</h3>"]
        for line in lines:
            if line.startswith("http://") or line.startswith("https://"):
                out += ["<p><a href=\"", html.escape(line, quote=True), "\">", html.escape(line), "</a></p>"]
            else:
                out += ["<p style=\"white-space:pre-wrap\">", html.escape(line), "</p>"]
    out += ["<p>", html.escape(FOOTER), "</p>"]
    return "".join(out)


def prepare_message(incident, context=None):
    """Render the alert. Without `context` this is the raise-time message (blue_agent calls it
    with the bare incident dict); with `report_context(incident)` it is the full review report."""
    sender, recipients = os.getenv("ALERT_FROM", ""), os.getenv("ALERT_TO", "")
    if len(_addresses(sender)) != 1:
        raise MailError("ALERT_FROM must contain one sender", retryable=False)
    to = list(dict.fromkeys(address for _, address in _addresses(recipients)))
    if len(to) > 50:
        raise MailError("At most 50 alert recipients are supported", retryable=False)
    test = incident.get("attack_type") == "notification_test"
    severity = str(incident.get("severity", "info")).upper().replace("\r", "").replace("\n", "")[:20]
    subject = "[TEST] Bastion alert delivery check" if test else f"[{severity}] Bastion security incident"
    intro = "BASTION TEST EMAIL — no attack occurred." if test else "BASTION SECURITY INCIDENT"
    fields = [("Severity", severity), ("Type", incident.get("attack_type", "unknown")),
              ("Source", incident.get("source_ip", "unknown")), ("Time (UTC)", incident.get("ts", "unknown")),
              ("Case", incident.get("case_id", "manual")), ("Summary", incident.get("summary", ""))]
    if context is None:
        fields.append(("Evidence", incident.get("evidence", "")))
        text = intro + "\n\n" + "\n\n".join(f"{label}: {str(value)[:2000]}" for label, value in fields)
        text += "\n\n" + FOOTER + "\n"
        return {"provider": "resend", "from": sender, "to": to, "subject": subject,
                "text": text, "html": "<h2>" + html.escape(subject) + "</h2><pre style=\"white-space:pre-wrap\">" + html.escape(text) + "</pre>"}
    sections = _report_sections(incident, context)
    text = intro + "\n\n" + "\n".join(f"{label}: {str(value)[:2000]}" for label, value in fields)
    for heading, lines in sections:
        text += "\n\n" + heading.upper() + "\n" + "\n".join(lines)
    text += "\n\n" + FOOTER + "\n"
    return {"provider": "resend", "from": sender, "to": to, "subject": subject, "enriched": True,
            "text": text, "html": _html_report(subject, intro, fields, sections)}


def _deliver_local(message, delivery_key):
    """No RESEND_API_KEY: don't drop the alert, don't crash-loop. Write it where a
    local demo can see it instead (file + stdout), same shape as a MailHog catcher.

    ponytail: one JSONL file + a print, not a MailHog container/service. Good
    enough to see alerts fire locally; swap to real Resend by setting a key.
    """
    LOCAL_OUTBOX.parent.mkdir(parents=True, exist_ok=True)
    with LOCAL_OUTBOX.open("a") as fh:
        fh.write(json.dumps({**message, "provider": "local", "id": delivery_key}) + "\n")
    print(f"[local-mail] (no RESEND_API_KEY set) {message['subject']} -> {', '.join(message['to'])}\n"
          f"{message['text']}\n--- also appended to {LOCAL_OUTBOX} ---", flush=True)
    return {"provider": "local", "provider_id": delivery_key, "status": "accepted"}


def send_email(incident, *, transport=None):
    # Capture sender/recipients/content at enqueue time so retries cannot silently
    # change the payload attached to a provider idempotency key.
    message = incident.get("_mail") or prepare_message(incident)
    key = incident.get("_mail_key") or hashlib.sha256(json.dumps(message, sort_keys=True).encode()).hexdigest()
    delivery_key = "bastion/" + hashlib.sha256(key.encode()).hexdigest()
    api_key = validate_config()
    if api_key is None:
        return _deliver_local(message, delivery_key)
    payload = {k: message[k] for k in ("from", "to", "subject", "text", "html")}
    # Fixed endpoint; a configured secret is never sent to an arbitrary host.
    try:
        with httpx.Client(timeout=10, transport=transport, follow_redirects=False) as client:
            response = client.post("https://api.resend.com/emails", json=payload,
                                   headers={"Authorization": f"Bearer {api_key}", "Idempotency-Key": delivery_key})
    except httpx.HTTPError:
        raise MailError("Resend network request failed; retry with the same idempotency key") from None
    if not 200 <= response.status_code < 300:
        retryable = response.status_code in {408, 429} or response.status_code >= 500
        try:
            retry_after = max(1, min(3600, int(response.headers.get("retry-after", "60"))))
        except ValueError:
            retry_after = 60
        explanations = {401: "check the API key", 403: "check domain verification, recipient restrictions and key permissions",
                        409: "idempotency conflict; inspect the Resend log", 422: "check sender and recipient configuration",
                        429: "Resend rate limit or quota reached"}
        raise MailError(f"Resend HTTP {response.status_code}: {explanations.get(response.status_code, 'check the Resend email log')}",
                        retryable, retry_after)
    try:
        email_id = response.json()["id"]
        if not isinstance(email_id, str) or not email_id or len(email_id) > 200:
            raise ValueError()
    except (ValueError, KeyError, TypeError):
        raise MailError("Resend response lacked an email ID; retry with the same idempotency key") from None
    return {"provider": "resend", "provider_id": email_id, "status": "accepted"}
